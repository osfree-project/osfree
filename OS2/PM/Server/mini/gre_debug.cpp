/*!
 * @brief Return a symbolic name for an NGre* code.
 *
 * Chooses the table by bit 9 (mask 0x0200) and looks up by low byte.
 * Returns "?" for unused low bytes.
 */
const char *GreFuncName(ULONG fnCode)
{
    const char *name = (fnCode & 0x0200UL)
                       ? g_intNames[fnCode & 0xFF]
                       : g_drvNames[fnCode & 0xFF];
    return name ? name : "?";
}
